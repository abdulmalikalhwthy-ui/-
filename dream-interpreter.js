  function dreamRunSearch() {
    var input = document.getElementById('dreamSearchInput');
    if (!input) return;
    var q = input.value.trim();
    if (!q) { alert('⚠️ اكتب رمزاً للبحث'); return; }

    var normQ = q.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');

    var matches = [];
    for (var key in DREAMS_DB) {
      var keyNorm = key.replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');
      if (keyNorm.indexOf(normQ) !== -1 || normQ.indexOf(keyNorm) !== -1) {
        matches.push({ symbol: key, data: DREAMS_DB[key] });
        continue;
      }
      var kws = DREAMS_DB[key].keywords || [];
      for (var i = 0; i < kws.length; i++) {
        var kwNorm = kws[i].replace(/[أإآ]/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');
        if (kwNorm.indexOf(normQ) !== -1) {
          matches.push({ symbol: key, data: DREAMS_DB[key] });
          break;
        }
      }
    }

    var resultDiv = document.getElementById('dreamResult');
    if (!resultDiv) return;

    if (matches.length === 0) {
      resultDiv.innerHTML = '<div class="card"><p style="text-align:center;color:#888;padding:16px">لم يُعثر على رموز تطابق "' + q + '"</p></div>';
      return;
    }

    var html = matches.slice(0, 20).map(function (s) {
      return '<div class="list-item" onclick="dreamShowSymbol(\'' + s.symbol.replace(/'/g, "\\'") + '\')" style="cursor:pointer">' +
        '<div style="flex:1">' +
        '<div class="item-name" style="font-size:16px">' + s.symbol + '</div>' +
        '<div class="item-sub">' + s.data.meaning + '</div>' +
        '</div>' +
        '<div class="item-arrow">‹</div>' +
        '</div>';
    }).join("");

    resultDiv.innerHTML = '<div class="card"><div class="card-title">نتائج البحث (' + matches.length + ')</div>' + html + '</div>';
    window.scrollTo(0, document.body.scrollHeight);
  }

